-- GOLD TABLE
CREATE TABLE GOLD_CAMPAIGN_ELIGIBILITY AS 
SELECT 
    NVL(SCD.CUSTOMER_ID, -1) AS CUSTOMER_ID,
    NVL(SCD.FIRST_NAME, 'UNKNOWN') AS FIRST_NAME,
    NVL(SCD.LAST_NAME, 'UNKNOWN') AS LAST_NAME,
    NVL(SCD.PROVINCE, 'UNKNOWN') AS PROVINCE,
    SCCS.CREDIT_SCORE,
    NVL(Agg.TOTAL_DEPOSITS, 0) AS TOTAL_DEPOSITS,
    NVL(Agg.TRAVEL_COUNT, 0) AS TRAVEL_COUNT,
    TRUNC(MONTHS_BETWEEN(SYSDATE, TO_DATE(MIN(SCA.OPEN_DATE), 'YYYY-MM-DD')) / 12) AS ACC_AGE
FROM SILVER_CUSTOMER_DEMOGRAPHICS SCD 
JOIN SILVER_CUSTOMER_CREDIT_SCORE SCCS ON SCD.CUSTOMER_ID = SCCS.CUSTOMER_ID
JOIN SILVER_CUSTOMER_ACCOUNTS SCA ON SCD.CUSTOMER_ID = SCA.CUSTOMER_ID 
JOIN (
    SELECT
        SCA_SUB.CUSTOMER_ID,
        SUM(CASE WHEN SCT.AMOUNT > 0 THEN SCT.AMOUNT ELSE 0 END) AS TOTAL_DEPOSITS,
        COUNT(CASE WHEN SCT.TRANS_TYPE = 'TRAVEL' THEN 1 END) AS TRAVEL_COUNT
    FROM SILVER_CUSTOMER_ACCOUNTS SCA_SUB
    JOIN SILVER_CUSTOMER_TRANSACTIONS SCT ON SCA_SUB.ACCOUNT_ID = SCT.ACCOUNT_ID 
    WHERE SCA_SUB.ACCOUNT_STATUS = 'ACTIVE'
    GROUP BY SCA_SUB.CUSTOMER_ID 
) Agg ON SCD.CUSTOMER_ID = Agg.CUSTOMER_ID
GROUP BY
    SCD.CUSTOMER_ID,
    SCD.FIRST_NAME,
    SCD.LAST_NAME,
    SCD.PROVINCE,
    SCCS.CREDIT_SCORE,
    Agg.TOTAL_DEPOSITS,
    Agg.TRAVEL_COUNT;


-- FINAL MARKETING REPORT
CREATE TABLE FINAL_MARKETING_TARGETS AS
SELECT 
    FIRST_NAME,
    LAST_NAME,
    PROVINCE,
    TOTAL_DEPOSITS,
    CREDIT_SCORE,
    DENSE_RANK() OVER(PARTITION BY PROVINCE ORDER BY TOTAL_DEPOSITS DESC) AS RANKING
FROM (
    -- Subquery to clean the province first
    SELECT 
        FIRST_NAME,
        LAST_NAME,
        CASE 
            WHEN TRIM(PROVINCE) IN ('E. CAPE', 'EC', 'EASTERN CAPE') THEN 'EASTERN CAPE'
            WHEN TRIM(PROVINCE) IN ('WC', 'W CAPE', 'WESTERN CAPE') THEN 'WESTERN CAPE'
            WHEN TRIM(PROVINCE) IN ('GP', 'GAUTENG') THEN 'GAUTENG'
            WHEN TRIM(PROVINCE) IN ('KZN', 'KWAZULU NATAL', 'KWAZULU-NATAL') THEN 'KWAZULU-NATAL'
            WHEN TRIM(PROVINCE) IN ('LP', 'LIMPOPO') THEN 'LIMPOPO'
            WHEN TRIM(PROVINCE) IN ('NC', 'N CAPE', 'NORTHERN CAPE') THEN 'NORTHERN CAPE'
            WHEN TRIM(PROVINCE) IN ('NW', 'NORTH WEST', 'NORTH-WEST') THEN 'NORTH WEST'
            WHEN TRIM(PROVINCE) IN ('MP', 'MPUMALANGA') THEN 'MPUMALANGA'
            WHEN TRIM(PROVINCE) IN ('FS', 'FREE-STATE', 'FREE STATE') THEN 'FREE STATE'
            ELSE 'UNKNOWN'
        END AS PROVINCE,
        TOTAL_DEPOSITS,
        CREDIT_SCORE
    FROM GOLD_CAMPAIGN_ELIGIBILITY 
    WHERE 
        CREDIT_SCORE > 500 
        AND TOTAL_DEPOSITS > 15000
        AND TRAVEL_COUNT >= 2
        AND ACC_AGE > 2
) CLEAN_DATA;

